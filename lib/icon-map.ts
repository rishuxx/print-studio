export type IconName = keyof typeof iconRegistry;

import React from "react";

/** Resolves a string icon name from a data file. Falls back to a neutral mark. */
export function resolveIcon(name: string): LucideIcon {
  return (iconRegistry as Record<string, LucideIcon>)[name] ?? Shapes;
}

export function Icon({
  name,
  className,
  ...props
}: {
  name: string;
  className?: string;
} & React.SVGProps<SVGSVGElement>) {
  const Comp = resolveIcon(name);
  return React.createElement(Comp, { className, ...props });
}
